def generate_dataset(
    output_dir: str = "./dataset",
    n_unsafe: int = 800,
    n_non_dialogue: int = 800,
    n_waiting: int = 900,
    n_ready: int = 2200,
    n_confused: int = 900,
    context_ratio: float = 0.35,
    seed: int = 42,
):
    """
    生成完整的拒识模块BERT微调数据集

    参数:
        output_dir: 输出目录
        n_unsafe: unsafe标签样本数
        n_non_dialogue: non_dialogue标签样本数
        n_waiting: waiting标签样本数
        n_ready: ready标签样本数
        n_confused: confused标签样本数
        context_ratio: 含多轮上下文样本的比例 (0~1)
        seed: 随机种子
    """
    random.seed(seed)
    os.makedirs(output_dir, exist_ok=True)

    print("=" * 60)
    print("BERT 拒识模块微调数据集生成（家庭机器人场景版）")
    print("=" * 60)
    print(f"输出目录: {output_dir}")
    print(f"随机种子: {seed}")
    print(f"上下文比例: {context_ratio * 100:.0f}%")
    print()

    # Step 1: 生成各类别基础样本
    print("[1/4] 生成各类别基础样本...")
    dataset = []
    generators = [
        ("unsafe", n_unsafe, generate_unsafe),
        ("non_dialogue", n_non_dialogue, generate_non_dialogue),
        ("waiting", n_waiting, generate_waiting),
        ("ready", n_ready, generate_ready),
        ("confused", n_confused, generate_confused),
    ]

    for label, n, gen_func in generators:
        samples = gen_func(n)
        dataset.extend(samples)
        print(f"  {label}: {len(samples)}条")

    print(f"\n基础样本总计: {len(dataset)}条")

    # Step 2: 添加上下文
    print(f"\n[2/4] 添加多轮对话上下文 ({context_ratio * 100:.0f}%)...")
    dataset = add_context(dataset, context_ratio=context_ratio)
    ctx_count = sum(1 for s in dataset if " [SEP] " in s["text"])
    print(f"  含上下文: {ctx_count}条")
    print(f"  不含上下文: {len(dataset) - ctx_count}条")

    # Step 3: 划分数据集
    print("\n[3/4] 划分数据集 (8:1:1)...")
    train_data, val_data, test_data = split_dataset(dataset)
    print(f"  训练集: {len(train_data)}条")
    print(f"  验证集: {len(val_data)}条")
    print(f"  测试集: {len(test_data)}条")

    # Step 4: 保存文件
    print("\n[4/4] 保存JSONL文件...")
    save_jsonl(train_data, os.path.join(output_dir, "train.jsonl"))
    save_jsonl(val_data, os.path.join(output_dir, "val.jsonl"))
    save_jsonl(test_data, os.path.join(output_dir, "test.jsonl"))
    save_jsonl(dataset, os.path.join(output_dir, "dataset_all.jsonl"))

    # 统计报告
    print("\n" + "=" * 60)
    print("数据集统计报告")
    print("=" * 60)

    for name, data in [("训练集", train_data), ("验证集", val_data), ("测试集", test_data)]:
        print(f"\n{name} ({len(data)}条):")
        counts = Counter(s["label"] for s in data)
        for label in ["ready", "confused", "waiting", "unsafe", "non_dialogue"]:
            c = counts.get(label, 0)
            print(f"  {label:12s}: {c:4d} ({c / len(data) * 100:5.1f}%)")
        ctx = sum(1 for s in data if " [SEP] " in s["text"])
        print(f"  {'[多轮对话]':12s}: {ctx:4d} ({ctx / len(data) * 100:5.1f}%)")

    # Step 5: 保存版本元数据
    print("\n[5/5] 保存版本元数据...")
    metadata_path = os.path.join(output_dir, "metadata.json")

    # 自动递增版本号
    version = "1.0"
    if os.path.exists(metadata_path):
        try:
            with open(metadata_path, "r", encoding="utf-8") as f:
                old_meta = json.load(f)
                old_ver = old_meta.get("version", "1.0")
                try:
                    version = str(round(float(old_ver) + 0.1, 1))
                except ValueError:
                    version = old_ver + "_1"
        except Exception:
            pass

    metadata = {
        "version": version,
        "date": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "seed": seed,
        "context_ratio": context_ratio,
        "total_samples": len(dataset),
        "splits": {
            "train": len(train_data),
            "val": len(val_data),
            "test": len(test_data),
        },
        "distribution": {
            "ready": sum(1 for s in dataset if s["label"] == "ready"),
            "waiting": sum(1 for s in dataset if s["label"] == "waiting"),
            "confused": sum(1 for s in dataset if s["label"] == "confused"),
            "unsafe": sum(1 for s in dataset if s["label"] == "unsafe"),
            "non_dialogue": sum(1 for s in dataset if s["label"] == "non_dialogue"),
        },
        "context_stats": {
            "with_context": sum(1 for s in dataset if " [SEP] " in s["text"]),
            "without_context": sum(1 for s in dataset if " [SEP] " not in s["text"]),
        },
    }

    with open(metadata_path, "w", encoding="utf-8") as f:
        json.dump(metadata, f, ensure_ascii=False, indent=2)

    print(f"  版本: v{version}")
    print(f"  元数据: {metadata_path}")

    print("\n✅ 数据集生成完成！")
    return train_data, val_data, test_data


