def generate_ready(n: int) -> list:
    """生成完整且安全的正常输入样本（家庭机器人场景）"""
    samples = []
    seen = set()

    for category, texts in READY_CATEGORIES.items():
        for template in texts:
            # 填充可能的占位符
            text = fill_template(template, {**HISTORY_FILLERS, **SCIENCE_FILLERS, **CREATION_FILLERS, **HOLIDAY_FILLERS})

            # 规范化不完整的模板
            # 讲个X -> 讲个X的故事
            if text.startswith("讲个") and not any(kw in text for kw in ["故事", "寓言", "童话", "神话", "传说"]):
                text = text + "的故事"
            # 给我X -> 保持原样（不再加帮我）
            # 出个X -> 出个谜语给我猜 / 出个谜语（保持原样）

            if text not in seen:
                seen.add(text)
                samples.append({"text": text, "label": "ready"})
            # 口语化变体
            # 判断 text 是否是问句（更全面：含疑问词 且 不是命令句）
            has_question_word = any(q in text for q in ["谁", "什么", "怎么", "为什么", "多少", "哪里", "是不是", "对不对", "吗", "哪", "如何"])
            is_question = (
                has_question_word and
                not text.startswith("帮我") and
                not text.startswith("请") and
                not text.startswith("给我") and
                not text.startswith("陪我") and
                not text.startswith("跟我")
            )
            # 判断 text 是否已经是带前缀的命令句（只排除明确的前缀）
            has_prefix = any(text.startswith(p) for p in ["请", "请问", "我想"])
            # 判断 text 是否是邀请/命令类动词语义
            is_action_phrase = (
                any(text.startswith(v) for v in ["打开", "关闭", "播放", "设置", "提醒", "查询", "搜索",
                                                  "播放", "导航", "搜索", "拨打", "发送", "查看", "下载",
                                                  "告诉我", "介绍一下", "请介绍一下", "给我", "讲个",
                                                  "出个", "陪我", "跟我", "请我", "能不能"]) or
                any(text.startswith(v) for v in ["我们来", "玩"]) or
                text.startswith("帮我查") or
                text.startswith("帮我找") or
                text.startswith("帮我看") or
                text.startswith("帮我读") or
                text.startswith("帮我识别") or
                text.startswith("帮我翻译") or
                text.startswith("帮我检查") or
                text.startswith("帮我总结") or
                text.startswith("帮我播放") or
                text.startswith("帮我打开") or
                text.startswith("帮我关闭") or
                text.startswith("帮我调") or
                text.startswith("帮我设") or
                text.startswith("帮我问") or
                text.startswith("帮我告诉")
            )

            variants = []
            if not has_prefix:
                if is_question:
                    # 问句：只加问号或单独保留，不加其他后缀
                    variants.append(text + "？")
                    variants.append(text)
                    variants.append("那个" + text)
                else:
                    # 命令/陈述句：可以加多种前缀
                    # 只有非"给我/陪我/跟我/你当/你说"开头 且 不是完整游戏命令的才加帮我
                    is_game_cmd = any(text == cmd or text.startswith(cmd) for cmd in [
                        "脑筋急转弯", "歇后语接龙", "猜城市", "石头剪刀布",
                        "模拟超市", "玩故事", "玩成语", "我们来", "你当",
                        "开始外教口语", "结束外教口语", "进入外教口语", "退出外教口语",
                        "开始口语陪练", "结束口语陪练", "进入口语陪练", "退出口语陪练",
                        "开始英语陪练", "结束英语陪练", "进入英语陪练", "退出英语陪练",
                        "开始英语口语", "结束英语口语", "进入英语口语", "退出英语口语",
                        "开始陪我看电视", "结束陪我看电视",
                        "开始陪我聊天", "结束陪我聊天",
                        "开始陪我读书", "结束陪我读书",
                        "开始陪我做游戏", "结束陪我做游戏",
                        "开始陪我做作业", "结束陪我做作业",
                    ])
                    if not any(text.startswith(p) for p in ["给我", "陪我", "跟我", "你当", "你说"]) and not is_game_cmd:
                        variants.append("帮我" + text)
                    variants.append(text)
                    # 只有动词语义才加"能不能"
                    if is_action_phrase:
                        variants.append("能不能" + text)
                    variants.append("那个" + text)

                    # 情感类句子：可以加"小未"前缀，变成对机器人说的
                    is_emotion = any(text.startswith(emo) for emo in [
                        "我今天", "我有点", "我心里", "好累", "好开心", "好难过",
                        "好害怕", "好无聊", "好烦", "我需要", "我想", "我好"
                    ])
                    if is_emotion:
                        variants.append("小未，" + text)

            for v in variants:
                if v not in seen and random.random() > 0.3:
                    seen.add(v)
                    samples.append({"text": v, "label": "ready"})

    # 填充到目标数量
    attempts = 0
    max_attempts = n * 10
    while len(samples) < n:
        if attempts >= max_attempts:
            break
        category = random.choice(list(READY_CATEGORIES.keys()))
        base = random.choice(READY_CATEGORIES[category])
        text = fill_template(base, {**HISTORY_FILLERS, **SCIENCE_FILLERS, **CREATION_FILLERS, **HOLIDAY_FILLERS})
        prefix = random.choice(["", "帮我", "请", "我想", "能不能", "请问", "那个"])
        suffix = random.choice(["", "谢谢", "可以吗"])
        if prefix and text.startswith(prefix):
            text = text + suffix
        else:
            text = prefix + text + suffix
        if text not in seen:
            seen.add(text)
            samples.append({"text": text, "label": "ready"})
        attempts += 1

    return samples[:n]



