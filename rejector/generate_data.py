def generate_unsafe(n: int) -> list:
    """生成不安全内容样本"""
    samples = []
    seen = set()
    for template in UNSAFE_TEMPLATES:
        for _ in range(max(1, n // len(UNSAFE_TEMPLATES) + 5)):
            text = fill_template(template, UNSAFE_FILLERS)
            prefixes = ["", "那个，", "我想问一下", "请问", "你好，", "我想知道"]
            suffixes = ["", "？", "怎么弄", "求教"]
            text = random.choice(prefixes) + text + random.choice(suffixes)
            if text not in seen:
                seen.add(text)
                samples.append({"text": text, "label": "unsafe"})
    attempts = 0
    max_attempts = n * 10
    while len(samples) < n:
        if attempts >= max_attempts:
            break
        template = random.choice(UNSAFE_TEMPLATES)
        text = fill_template(template, UNSAFE_FILLERS)
        prefixes = ["", "那个...", "请问一下", "我想知道", "能不能告诉我", "你好，我想问"]
