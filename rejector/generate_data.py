def generate_waiting(n: int) -> list:
    """生成不完整输入样本"""
    samples = []
    seen = set()
    for pattern in WAITING_PATTERNS:
        if pattern not in seen:
            seen.add(pattern)
            samples.append({"text": pattern, "label": "waiting"})
        if "..." not in pattern:
            variant = pattern + "..."
            if variant not in seen:
                seen.add(variant)
                samples.append({"text": variant, "label": "waiting"})
    for _ in range(400):
        text = random.choice(WAITING_FRAGMENTS_START) + random.choice(WAITING_FRAGMENTS_END)
        if text not in seen and len(text) >= 2:
            seen.add(text)
            samples.append({"text": text, "label": "waiting"})
    fillers = ["嗯", "啊", "哦", "呃", "哎", "唔", "欸"]
    for _ in range(200):
        length = random.randint(2, 8)
        text = "".join(random.choice(fillers) for _ in range(length))
        if random.random() > 0.5:
            text += "..."
        if text not in seen:
            seen.add(text)
            samples.append({"text": text, "label": "waiting"})
    for text in WAITING_ASR_INCOMPLETE:
        if text not in seen:
            seen.add(text)
            samples.append({"text": text, "label": "waiting"})
        for filler in ["嗯...", "啊...", "那个..."]:
            variant = text + filler
            if variant not in seen:
                seen.add(variant)
                samples.append({"text": variant, "label": "waiting"})
    attempts = 0
    max_attempts = n * 10
    while len(samples) < n:
        if attempts >= max_attempts:
            break
        start = random.choice(["", "嗯...", "那个...", "就是...", "嗯嗯...", "等一下..."])
        mid = random.choice(WAITING_FRAGMENTS_START + WAITING_ASR_INCOMPLETE)
        end = random.choice(["...", "嗯", "啊", "哦", "呃", "那个...", "...那个"])
        text = (start + mid + end).replace("......", "...")
        if text not in seen and len(text) >= 2:
            seen.add(text)
            samples.append({"text": text, "label": "waiting"})
        attempts += 1
    return samples[:n]



