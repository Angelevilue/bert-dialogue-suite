def generate_non_dialogue(n: int) -> list:
    """生成非对话输入样本"""
    samples = []
    seen = set()
    for category, texts in NON_DIALOGUE_CATEGORIES.items():
        for text in texts:
            if text not in seen:
                seen.add(text)
                samples.append({"text": text, "label": "non_dialogue"})
    fillers_short = ["嗯", "啊", "哦", "呃", "哎"]
    sfx_chars = ["叮", "咚", "啪", "嘟", "哔"]
    attempts = 0
    max_attempts = n * 10
    while len(samples) < n:
        if attempts >= max_attempts:
            break
        category = random.choice(list(NON_DIALOGUE_CATEGORIES.keys()))
        base = random.choice(NON_DIALOGUE_CATEGORIES[category])
        transforms = [
            base,
            base * random.randint(2, 4),
            "".join(random.choice(fillers_short) for _ in range(random.randint(3, 10))),
            "".join(random.choice(sfx_chars) for _ in range(random.randint(3, 8))),
            "".join(str(i) for i in range(random.randint(1, 10))) * random.randint(1, 3),
        ]
        text = random.choice(transforms)
        if text not in seen and len(text) > 0:
            seen.add(text)
            samples.append({"text": text, "label": "non_dialogue"})
        attempts += 1
    return samples[:n]


