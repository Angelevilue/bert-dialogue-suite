def generate_confused(n: int) -> list:
    """生成意图不明确样本（含unclear_intent + robot_meta + garbage）"""
    samples = []
    seen = set()

    for text in CONFUSED_UNCLEAR:
        if text not in seen:
            seen.add(text)
            samples.append({"text": text, "label": "confused"})

    for text in CONFUSED_ROBOT_META:
        if text not in seen:
            seen.add(text)
            samples.append({"text": text, "label": "confused"})

    for text in CONFUSED_GARBAGE:
        if text not in seen:
            seen.add(text)
            samples.append({"text": text, "label": "confused"})

    garbage_patterns = ["{a}{b}{a}{b}", "{a}{a}{a}", "{a}{b}{c}{a}{b}{c}",
                        "{a}{a}{b}{b}", "{a}{b}{b}{a}"]
    attempts = 0
    max_attempts = n * 10
    while len(samples) < n:
        if attempts >= max_attempts:
            break
        pattern = random.choice(garbage_patterns)
        chars = random.sample(GARBAGE_CHARS, 3)
        text = pattern.format(a=chars[0], b=chars[1], c=chars[2])
        if text not in seen and len(text) >= 2:
            seen.add(text)
            samples.append({"text": text, "label": "confused"})
        attempts += 1

    return samples[:n]



